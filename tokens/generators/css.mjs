// Writes src/generated/tokens.css from the token JSON. Generated output is not committed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const walk = (node, path, out) => {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push({ path: [...path, k], token: v });
    else if (v && typeof v === 'object') walk(v, [...path, k], out);
  }
  return out;
};

const name = (path) => `--syn-${path.join('-')}`;
const ref = (value) => value.replace(/\{([^}]+)\}/g, (_, p) => `var(${name(p.split('.'))})`);
const quote = (f) => (/\s/.test(f) || /^[A-Z]/.test(f) ? `"${f}"` : f);

function format(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'fontFamily': return Array.isArray(v) ? v.map(quote).join(', ') : ref(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'shadow': return v.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} color-mix(in srgb, ${ref(s.color)} ${Math.round(s.alpha * 1000) / 10}%, transparent)`).join(', ');
    case 'string': return v;
    default: return typeof v === 'string' ? ref(v) : String(v);
  }
}

const declare = (entries) => entries.map(({ path, token }) => `  ${name(path)}: ${format(token)};`).join('\n');

export function writeCss(root, themeNames, scales) {
  const sizeAdjustPercent = scales.figureFace.sizeAdjustPercent;
  const read = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));
  const shared = [...walk(read('tokens/semantic/scales.json'), [], []), ...walk(read('tokens/primitives/figure-face.json'), [], [])]
    .filter((e) => e.path.join('.') !== 'figure.size-adjust');
  const blocks = [
    '/* Generated by tokens/generators. Do not edit. */',
    `@font-face {\n  font-family: "Syn Figure";\n  src: url("../../node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2") format("woff2");\n  font-weight: 100 900;\n  font-style: normal;\n  font-display: swap;\n  size-adjust: ${sizeAdjustPercent}%;\n}`,
    `:root {\n${declare(shared)}\n}`,
  ];
  for (const t of themeNames) {
    const entries = walk(read(`tokens/themes/${t.name}.json`), [], []);
    blocks.push(`[data-syn-theme="${t.name}"] {\n  color-scheme: ${t.polarity};\n${declare(entries)}\n}`);
  }
  const file = join(root, 'src', 'generated', 'tokens.css');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${blocks.join('\n\n')}\n`);

  const px = (group) => Object.fromEntries(Object.entries(group).map(([k, v]) => [k.replace(/^[a-z]+-/, ''), v.px]));
  const ts = [
    '// Generated by tokens/generators. Do not edit.',
    `export const breakpointPx = ${JSON.stringify(px(scales.breakpoints))} as const;`,
    `export const iconPx = ${JSON.stringify(px(scales.icon))} as const;`,
    '',
  ].join('\n');
  writeFileSync(join(root, 'src', 'generated', 'tokens.ts'), ts);
}
