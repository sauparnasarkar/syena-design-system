// Token build, stage two: DTCG JSON in, src/generated/tokens.css and tokens.ts out, plus the
// token-count report. Stage one (tokens/generators) computes the JSON and validates it.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));
const themeNames = ['night', 'tidewater'];
const range = { min: 150, max: 300 };

StyleDictionary.registerTransform({ name: 'name/syn', type: 'name', transform: (token) => `--syn-${token.path.join('-')}` });

const variable = (path) => `--syn-${path.join('-')}`;
const ref = (value) => value.replace(/\{([^}]+)\}/g, (_, p) => `var(${variable(p.split('.'))})`);
const quote = (family) => (/\s/.test(family) || /^[A-Z]/.test(family) ? `"${family}"` : family);

/** The CSS value of a token, with references kept as var() so themes override them. */
function cssValue(token) {
  const v = token.original.$value;
  switch (token.$type ?? token.type) {
    case 'fontFamily': return Array.isArray(v) ? v.map(quote).join(', ') : ref(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'shadow': return v.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} color-mix(in srgb, ${ref(s.color)} ${Math.round(s.alpha * 1000) / 10}%, transparent)`).join(', ');
    default: return typeof v === 'string' ? ref(v) : String(v);
  }
}

const emitted = (token) => token.isSource && token.path.join('.') !== 'figure.size-adjust';
const declarations = (dictionary) => dictionary.allTokens.filter(emitted).map((t) => `  ${t.name}: ${cssValue(t)};`);

StyleDictionary.registerFormat({
  name: 'syn/css-block',
  format: ({ dictionary, options }) => `${options.selector} {\n${options.colorScheme ? `  color-scheme: ${options.colorScheme};\n` : ''}${declarations(dictionary).join('\n')}\n}\n`,
});

const instance = async (source, include, selector, colorScheme) => {
  const sd = new StyleDictionary({
    usesDtcg: true,
    source,
    include,
    log: { verbosity: 'silent', warnings: 'warn', errors: { brokenReferences: 'throw' } },
    platforms: {
      css: {
        transforms: ['name/syn'],
        files: [{ destination: 'unused.css', format: 'syn/css-block', options: { selector, colorScheme } }],
      },
    },
  });
  const [{ output }] = await sd.formatPlatform('css');
  const { allTokens } = await sd.getPlatformTokens('css');
  return { output, tokens: allTokens.filter(emitted), all: allTokens };
};

const nest = (tokens, accept) => {
  const out = {};
  for (const t of tokens) {
    if (!accept(t)) continue;
    let node = out;
    t.path.slice(0, -1).forEach((k) => { node = node[k] ??= {}; });
    node[t.path[t.path.length - 1]] = t.$value ?? t.value;
  }
  return out;
};
const plain = (t) => (t.$type ?? t.type) !== 'shadow';

export async function buildTokens() {
  const inputs = read('tokens/generators/inputs.json');
  const rootPx = inputs.type.rootPx;
  const base = await instance(['tokens/semantic/scales.json', 'tokens/primitives/figure-face.json'].map((p) => join(root, p)), [join(root, 'tokens/themes/night.json')], ':root');
  const themes = {};
  for (const name of themeNames) {
    const scheme = name === 'night' ? 'dark' : 'light';
    themes[name] = await instance([join(root, `tokens/themes/${name}.json`)], [], `[data-syn-theme="${name}"]`, scheme);
  }

  const sizeAdjust = read('tokens/primitives/figure-face.json').figure['size-adjust'].$value;
  const css = [
    '/* Generated by the token build. Do not edit. */',
    `@font-face {\n  font-family: "Syn Figure";\n  src: url("../../node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2") format("woff2");\n  font-weight: 100 900;\n  font-style: normal;\n  font-display: swap;\n  size-adjust: ${Math.round(sizeAdjust * 10000) / 100}%;\n}`,
    base.output.trimEnd(),
    ...themeNames.map((n) => themes[n].output.trimEnd()),
  ].join('\n\n');

  const px = (group) => Object.fromEntries(Object.entries(group).map(([k, v]) => [k, Math.round(parseFloat(v) * rootPx)]));
  const scale = nest(base.all, (t) => t.isSource && plain(t));
  const ts = [
    '// Generated by the token build. Do not edit.',
    `export const rootPx = ${rootPx};`,
    `export const scale = ${JSON.stringify(scale, null, 2)} as const;`,
    `export const themes = ${JSON.stringify(Object.fromEntries(themeNames.map((n) => [n, nest(themes[n].tokens, plain)])), null, 2)} as const;`,
    'export type ThemeName = keyof typeof themes;',
    `export const breakpointPx = ${JSON.stringify(px(scale.breakpoint))} as const;`,
    `export const iconPx = ${JSON.stringify(px(scale.icon))} as const;`,
    '',
  ].join('\n');

  const dir = join(root, 'src', 'generated');
  mkdirSync(join(dir, 'reports'), { recursive: true });
  writeFileSync(join(dir, 'tokens.css'), `${css}\n`);
  writeFileSync(join(dir, 'tokens.ts'), ts);

  // Token-count report: distinct custom properties emitted, by category.
  const names = new Set([...base.tokens, ...themes.night.tokens].map((t) => t.name));
  const byCategory = {};
  for (const t of [...base.tokens, ...themes.night.tokens]) byCategory[t.path[0]] = (byCategory[t.path[0]] ?? 0) + 1;
  const total = names.size;
  const report = { total, range, withinRange: total >= range.min && total <= range.max, byCategory, perTheme: Object.fromEntries(themeNames.map((n) => [n, themes[n].tokens.length])), sharedByAllThemes: base.tokens.length };
  writeFileSync(join(dir, 'reports', 'token-count.json'), `${JSON.stringify(report, null, 2)}\n`);
  return report;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const report = await buildTokens();
  console.log(`tokens: ${report.total} custom properties (${Object.entries(report.byCategory).map(([k, v]) => `${k} ${v}`).join(', ')})`);
  if (!report.withinRange) {
    console.error(`token count ${report.total} is outside the target range ${range.min} to ${range.max}`);
    process.exit(1);
  }
}
